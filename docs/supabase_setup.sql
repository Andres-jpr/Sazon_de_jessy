create extension if not exists "pgcrypto";

create table if not exists public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre text,
  rol text not null default 'admin' check (rol in ('admin', 'empleado')),
  creado_en timestamptz not null default now()
);

create table if not exists public.categorias (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  icono text not null default '',
  orden integer not null default 0,
  activa boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.productos (
  id uuid primary key default gen_random_uuid(),
  codigo_original integer unique,
  categoria_id uuid references public.categorias(id) on delete set null,
  nombre text not null,
  descripcion text not null default '',
  precio numeric(10,2) not null check (precio >= 0),
  imagen_url text,
  insignia text not null default '',
  disponible boolean not null default true,
  popular boolean not null default false,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.configuracion_sitio (
  id integer primary key default 1 check (id = 1),
  nombre_restaurante text not null default 'La Sazon de Jessy',
  slogan text not null default '',
  descripcion text not null default '',
  whatsapp_numero text,
  whatsapp_visible text,
  whatsapp_mensaje_bienvenida text,
  direccion text,
  referencia text,
  google_maps_url text,
  moneda text not null default '$',
  nota_pedido text,
  modo_horario text not null default 'auto'
    check (modo_horario in ('auto', 'manual_abierto', 'manual_cerrado')),
  banner_promo_activo boolean not null default true,
  banner_promo_texto text,
  beneficios jsonb not null default '[]'::jsonb,
  apariencia jsonb not null default '{}'::jsonb,
  actualizado_en timestamptz not null default now()
);

create table if not exists public.horarios (
  id uuid primary key default gen_random_uuid(),
  dia_semana integer not null unique check (dia_semana between 0 and 6),
  hora_apertura time,
  hora_cierre time,
  cerrado boolean not null default false,
  texto_visible text
);

create table if not exists public.metodos_pago (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  icono text,
  detalle text,
  activo boolean not null default true,
  orden integer not null default 0
);

create table if not exists public.pedidos (
  id uuid primary key default gen_random_uuid(),
  numero_pedido bigint generated by default as identity unique,
  cliente_nombre text not null,
  cliente_telefono text,
  tipo_pedido text not null default 'retiro'
    check (tipo_pedido in ('retiro', 'delivery')),
  direccion_entrega text,
  notas text,
  metodo_pago text,
  subtotal numeric(10,2) not null default 0 check (subtotal >= 0),
  costo_envio numeric(10,2) not null default 0 check (costo_envio >= 0),
  total numeric(10,2) not null default 0 check (total >= 0),
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'confirmado', 'preparando', 'listo', 'entregado', 'cancelado')),
  origen text not null default 'web'
    check (origen in ('web', 'whatsapp', 'admin')),
  whatsapp_mensaje text,
  whatsapp_enviado boolean not null default false,
  whatsapp_enviado_en timestamptz,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.pedido_items (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references public.pedidos(id) on delete cascade,
  producto_id uuid references public.productos(id) on delete set null,
  nombre_producto text not null,
  precio_unitario numeric(10,2) not null check (precio_unitario >= 0),
  cantidad integer not null check (cantidad > 0),
  subtotal numeric(10,2) not null check (subtotal >= 0)
);

