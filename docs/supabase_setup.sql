-- Vista para el panel administrativo. Hereda el RLS de las tablas base.
drop view if exists public.pedidos_resumen;
create view public.pedidos_resumen
with (security_invoker = true)
as
select
  p.id, p.numero_pedido, p.cliente_nombre, p.cliente_telefono,
  p.tipo_pedido, p.direccion_entrega, p.metodo_pago, p.subtotal,
  p.costo_envio, p.total, p.estado, p.origen, p.whatsapp_enviado,
  p.creado_en,
  coalesce(
    jsonb_agg(jsonb_build_object(
      'nombre', pi.nombre_producto,
      'cantidad', pi.cantidad,
      'precio', pi.precio_unitario,
      'subtotal', pi.subtotal
    ) order by pi.id) filter (where pi.id is not null),
    '[]'::jsonb
  ) as items
from public.pedidos p
left join public.pedido_items pi on pi.pedido_id = p.id
group by p.id;

